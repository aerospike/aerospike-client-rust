#!/usr/bin/env python3
"""Generate the tutorial chapter of the book from its template and the tutorial sources.

The tutorial shows every step in all five languages. The code lives in real source files under
`tutorial/`, one per language, each step between `ANCHOR: name` and `ANCHOR_END: name` comments, so the
snippets are compiled, not typed into a page:

    tutorial/rust/src/lib.rs    cargo check --target wasm32-unknown-unknown
    tutorial/go/main.go         go run .../cmd/udfgen && GOOS=wasip1 GOARCH=wasm go vet .
    tutorial/c/tutorial.c       clang --target=wasm32 -fsyntax-only -I<c sdk>/include
    tutorial/cpp/tutorial.cpp   clang++ --target=wasm32 -std=c++20 -fsyntax-only -I<cpp sdk>/include -I<c sdk>/include
    tutorial/java/Tutorial.java javac against the SDK, with its annotation processor

The template `tutorial/record-udfs.md` is the prose. A line `{{snippet name}}`
becomes that step in every language, one labelled block after another; `{{snippet name: c}}` (any list of
languages) only those. The output goes to `src/record-udfs/tutorial.md`.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'tutorial')

# Language key, label in the page, fence language, source file.
LANGS = [
    ('rust', 'Rust', 'rust', os.path.join('rust', 'src', 'lib.rs')),
    ('go', 'Go', 'go', os.path.join('go', 'main.go')),
    ('c', 'C', 'c', os.path.join('c', 'tutorial.c')),
    ('cpp', 'C++', 'cpp', os.path.join('cpp', 'tutorial.cpp')),
    ('java', 'Java', 'java', os.path.join('java', 'Tutorial.java')),
]

PAGES = [
    ('record-udfs.md', os.path.join('src', 'record-udfs', 'tutorial.md')),
]

ANCHOR = re.compile(r'^\s*//\s*ANCHOR(_END)?:\s*(\w+)\s*$')
DIRECTIVE = re.compile(r'^\{\{snippet (\w+)(?::\s*([\w, ]+))?\}\}\s*$')


def anchors(path):
    """Every anchored region of a source file, by name, as its lines."""
    found, open_ = {}, {}
    with open(path, encoding='utf-8') as f:
        for number, line in enumerate(f, 1):
            m = ANCHOR.match(line)
            if m is None:
                for lines in open_.values():
                    lines.append(line.rstrip('\n'))
                continue
            end, name = m.group(1), m.group(2)
            if end:
                if name not in open_:
                    sys.exit(f'{path}:{number}: ANCHOR_END: {name} without its ANCHOR')
                found[name] = open_.pop(name)
            else:
                if name in open_ or name in found:
                    sys.exit(f'{path}:{number}: ANCHOR: {name} twice')
                open_[name] = []
    if open_:
        sys.exit(f'{path}: ANCHOR without ANCHOR_END: {", ".join(open_)}')
    return found


def tidy(lines):
    """Leading tabs as four spaces, the common indent and the blank lines around the region removed."""
    out = []
    for line in lines:
        body = line.lstrip('\t')
        out.append(('    ' * (len(line) - len(body)) + body).rstrip())
    while out and not out[0]:
        out.pop(0)
    while out and not out[-1]:
        out.pop()
    indent = min((len(l) - len(l.lstrip(' ')) for l in out if l), default=0)
    return [l[indent:] for l in out]


def main():
    sources = {key: anchors(os.path.join(SRC, path)) for key, _, _, path in LANGS}
    used = {key: set() for key in sources}

    for template, target in PAGES:
        out = [f'<!-- generated by book/gen-tutorial.py from book/tutorial/{template}; do not edit -->', '']
        with open(os.path.join(SRC, template), encoding='utf-8') as f:
            for number, line in enumerate(f, 1):
                m = DIRECTIVE.match(line)
                if m is None:
                    out.append(line.rstrip('\n'))
                    continue
                name = m.group(1)
                only = [w.strip() for w in m.group(2).split(',')] if m.group(2) else None
                for key, label, fence, _ in LANGS:
                    if only is not None and key not in only:
                        continue
                    if name not in sources[key]:
                        sys.exit(f'tutorial/{template}:{number}: no ANCHOR: {name} in the {label} source')
                    used[key].add(name)
                    out += [f'**{label}**', '', f'```{fence}'] + tidy(sources[key][name]) + ['```', '']
                if out[-1] == '':
                    out.pop()
        with open(os.path.join(HERE, target), 'w', encoding='utf-8') as f:
            f.write('\n'.join(out).rstrip('\n') + '\n')
        print(f'wrote {target}')

    for key, label, _, _ in LANGS:
        spare = sorted(set(sources[key]) - used[key])
        if spare:
            print(f'note: the {label} source has anchors no page uses: {", ".join(spare)}')


if __name__ == '__main__':
    main()
