#!/usr/bin/env python3
"""Generate the API reference chapters of the book from the four SDK sources.

Reads `aerospike-udf-sdk-wasm/src/lib.rs`, `aerospike-udf-sdk-wasm-go/udf.go`,
`aerospike-udf-sdk-wasm-c/include/aerospike_udf.h` and the Java SDK's classes under
`aerospike-udf-sdk-wasm-java/sdk`, takes every public item with the comment above it, and
writes `src/api/<lang>-<area>.md` for the areas record, stream and events. The guide chapters include those
files, so the reference is complete by construction and regenerated by `python3 gen-api.py` whenever an
SDK changes.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, 'src', 'api')

RUST = os.path.join(ROOT, 'aerospike-udf-sdk-wasm', 'src', 'lib.rs')
GO_DIR = os.path.join(ROOT, 'aerospike-udf-sdk-wasm-go')
# The Go package's files and the area each belongs to; udf.go decides by its section comments.
GO_FILES = [('udf.go', None), ('errors.go', 'record'), ('record.go', 'record'), ('value.go', 'record'),
            ('coll.go', 'record'), ('result.go', 'record'), ('args.go', 'record'), ('events.go', 'events')]
C = os.path.join(ROOT, 'aerospike-udf-sdk-wasm-c', 'include', 'aerospike_udf.h')
CPP = os.path.join(ROOT, 'aerospike-udf-sdk-wasm-cpp', 'include', 'aerospike_udf.hpp')
JAVA_DIR = os.path.join(ROOT, 'aerospike-udf-sdk-wasm-java', 'sdk', 'src', 'main', 'java', 'com', 'aerospike', 'udf')
# Which class belongs to which area of the book.
JAVA_FILES = [('record', 'Function.java'), ('record', 'Nullable.java'), ('record', 'UdfException.java'),
              ('record', 'Record.java'), ('record', 'RecordReader.java'), ('record', 'Value.java'),
              ('record', 'ListValue.java'), ('record', 'MapValue.java'),
              ('record', 'ListBuilder.java'), ('record', 'MapBuilder.java'), ('record', 'Udf.java'),
              ('record', 'LowLevel.java'), ('record', 'Params.java'),
              ('stream', 'Stream.java'),
              ('events', 'On.java'), ('events', 'Resolution.java'),
              ('events', 'EventRecord.java'), ('events', 'Conflict.java'), ('events', 'Pair.java'),
              ('events', 'Both.java')]

EVENT_SECTIONS = {'Events'}


def area_of(section, name=''):
    if section in EVENT_SECTIONS:
        return 'events'
    if name in ('stream', 'stream!'):
        return 'stream'
    return 'record'


# ---------------------------------------------------------------- rust

def parse_rust(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    items = []  # (area, kind, name, signature, doc, body)
    section = ''
    impl_of = None
    doc = []
    hidden = False
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        s = line.strip()
        if s.startswith('//====') and i + 1 < n and lines[i + 1].startswith('// '):
            section = lines[i + 1][3:].rstrip('.').strip()
            i += 2
            continue
        if s.startswith('///'):
            doc.append(s[3:].strip())
            i += 1
            continue
        if s.startswith('#[doc(hidden)]'):
            hidden = True
            i += 1
            continue
        if s.startswith('#['):
            i += 1
            continue
        if line.startswith('impl') and line.rstrip().endswith('{'):
            m = re.match(r'impl(?:<[^>]*>)?\s+(?:(\S+)\s+for\s+)?(\S+)', line)
            if m and m.group(1):
                items.append((area_of(section), 'impl', f'impl {m.group(1)} for {m.group(2)}', line.rstrip(' {'), doc, ''))
                impl_of = None
                depth = 1
                i += 1
                while i < n and depth > 0:
                    depth += lines[i].count('{') - lines[i].count('}')
                    i += 1
                doc = []
                continue
            impl_of = m.group(2) if m else None
            doc = []
            i += 1
            continue
        if line.startswith('}'):
            impl_of = None
        m = re.match(r'^(\s*)pub (?:unsafe )?(fn|struct|enum|trait|type|const|static)\s+([A-Za-z_][A-Za-z0-9_]*)', line)
        if m and not hidden:
            indent, kind, name = m.group(1), m.group(2), m.group(3)
            if indent == '' or (indent == '    ' and impl_of is not None):
                sig = [line.strip()]
                j = i
                while not (lines[j].rstrip().endswith('{') or lines[j].rstrip().endswith(';')):
                    j += 1
                    sig.append(lines[j].strip())
                signature = ' '.join(sig).rstrip('{;').strip()
                body = ''
                if kind in ('enum', 'struct') and lines[j].rstrip().endswith('{'):
                    k = j + 1
                    body_lines = []
                    while k < n and not lines[k].startswith('}'):
                        body_lines.append(lines[k])
                        k += 1
                    if kind == 'enum' or any(l.strip().startswith('pub ') for l in body_lines):
                        body = '\n'.join([lines[j].rstrip()] + body_lines + ['}'])
                    j = k
                full = f'{impl_of}::{name}' if impl_of and kind == 'fn' else name
                items.append((area_of(section, name), kind, full, signature, doc, body))
                i = j + 1
                doc = []
                hidden = False
                continue
        m = re.match(r'^macro_rules! (\w+)', line)
        if m:
            name = m.group(1) + '!'
            prev = lines[i - 1].strip() if i > 0 else ''
            if prev == '#[macro_export]' or (i > 1 and lines[i - 2].strip() == '#[macro_export]'):
                items.append((area_of(section, name), 'macro', name, f'macro_rules! {m.group(1)}', doc, ''))
            doc = []
            hidden = False
            depth = 1
            i += 1
            while i < n and depth > 0:
                depth += lines[i].count('{') - lines[i].count('}')
                i += 1
            continue
        if s == '':
            doc = []
            hidden = False
        i += 1
    return items


# ---------------------------------------------------------------- go

def parse_go_all():
    items = []
    for name, area in GO_FILES:
        parsed = parse_go(os.path.join(GO_DIR, name))
        if area:
            parsed = [(area,) + it[1:] for it in parsed]
        items.extend(parsed)
    return items


def parse_go(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    items = []
    section = ''
    doc = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        s = line.strip()
        if (s.startswith('//====') or s.startswith('//----')) and i + 1 < n and lines[i + 1].startswith('// '):
            section = lines[i + 1][3:].rstrip('.').strip()
            i += 2
            continue
        if s.startswith('//go:'):
            i += 1
            continue
        if s.startswith('//'):
            doc.append(s[2:].strip())
            i += 1
            continue
        m = re.match(r'^func (?:\((\w+) \*?(\w+)(?:\[[^\]]*\])?\) )?([A-Z]\w*)(?:\[[^\]]*\])?\(', line)
        if m:
            recv, name = m.group(2), m.group(3)
            signature = line.rstrip(' {').strip()
            full = f'{recv}.{name}' if recv else name
            items.append((area_of(section, name), 'func', full, signature, doc, ''))
            doc = []
            i += 1
            continue
        m = re.match(r'^type ([A-Z]\w*)(?:\[[^\]]*\])? (struct|interface)', line)
        if m and line.rstrip().endswith('}'):
            # A struct or interface written on one line, `type Decision struct{ Answer }`: the
            # declaration is its own body. Reading on for a closing brace would swallow every item
            # up to the next multi-line declaration's.
            items.append((area_of(section), 'type', m.group(1), line.strip(), doc, ''))
            doc = []
            i += 1
            continue
        if m:
            k = i + 1
            body = [line]
            while k < n and not lines[k].startswith('}'):
                body.append(lines[k])
                k += 1
            body.append('}')
            items.append((area_of(section), 'type', m.group(1), line.rstrip(' {').strip(), doc, '\n'.join(body)))
            doc = []
            i = k + 1
            continue
        m = re.match(r'^type ([A-Z]\w*)(?:\[[^\]]*\])? ', line)
        if m:
            items.append((area_of(section), 'type', m.group(1), line.strip(), doc, ''))
            doc = []
            i += 1
            continue
        if line.startswith('const (') or line.startswith('var ('):
            k = i + 1
            body = [line]
            while k < n and not lines[k].startswith(')'):
                body.append(lines[k])
                k += 1
            body.append(')')
            names = re.findall(r'^\s+([A-Z]\w*)', '\n'.join(body[1:]), re.M)
            title = 'constants: ' + ', '.join(names[:6]) + (', …' if len(names) > 6 else '')
            items.append((area_of(section), 'const', title, line.strip(), doc, '\n'.join(body)))
            doc = []
            i = k + 1
            continue
        if s == '':
            doc = []
        i += 1
    return items


# ---------------------------------------------------------------- c

def parse_c(path):
    text = open(path, encoding='utf-8').read()
    lines = text.split('\n')
    items = []
    section = ''
    doc = []
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        s = line.strip()
        if (s.startswith('/*====') or s.startswith('/*----')) and i + 1 < n and lines[i + 1].startswith(' * '):
            section = lines[i + 1][3:].rstrip('.').strip()
            while i < n and not lines[i].strip().endswith('*/'):
                i += 1
            i += 1
            continue
        if s.startswith('/*'):
            comment = [s[2:].strip()]
            while not lines[i].strip().endswith('*/'):
                i += 1
                comment.append(lines[i].strip().lstrip('*').strip())
            comment[-1] = comment[-1].rstrip('*/').strip()
            doc = [c for c in comment if c]
            i += 1
            continue
        m = re.match(r'^AS_UDF_IMPORT\((\w+)\)\s+(.*);', line)
        if m:
            items.append((area_of(section, m.group(1)), 'import', m.group(1), m.group(2).strip(), doc, ''))
            doc = []
            i += 1
            continue
        m = re.match(r'^static inline (.*?\b(as_udf_\w+)\(.*)', line)
        if m:
            signature = m.group(1).rstrip(' {').strip()
            items.append((area_of(section, m.group(2)), 'function', m.group(2), signature, doc, ''))
            doc = []
            i += 1
            continue
        m = re.match(r'^#define (AS_UDF_[A-Z_]+)(\(.*?\))?', line)
        if m:
            name = m.group(1)
            if name.startswith('AS_UDF_NO_LIBC'):
                i += 1
                continue
            body = [line]
            while lines[i].rstrip().endswith('\\'):
                i += 1
                body.append(lines[i])
            kind = 'macro' if m.group(2) else 'constant'
            items.append((area_of(section, name), kind, name + (m.group(2) or ''), '', doc, '\n'.join(body) if kind == 'macro' else line.strip()))
            doc = []
            i += 1
            continue
        m = re.match(r'^typedef struct (\w+)_s \{', line)
        if m:
            k = i
            body = []
            while not lines[k].startswith('}'):
                body.append(lines[k])
                k += 1
            body.append(lines[k])
            name = lines[k].strip().lstrip('}').strip().rstrip(';').strip()
            items.append((area_of(section, name), 'struct', name, '', doc, '\n'.join(body)))
            doc = []
            i = k + 1
            continue
        if s == '':
            doc = []
        i += 1
    return items


# ---------------------------------------------------------------- java

def parse_java(path, area):
    lines = open(path, encoding='utf-8').read().split('\n')
    items = []
    doc = []
    stack = []  # (class name, depth at which it opened)
    depth = 0
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        s = line.strip()
        if s.startswith('/**'):
            comment = [s[3:].strip()]
            while not lines[i].strip().endswith('*/'):
                i += 1
                comment.append(lines[i].strip().lstrip('*').strip())
            comment[-1] = comment[-1].rstrip('*/').strip()
            doc = [re.sub(r'\{@literal ([^}]*)\}', r'\1',
                          re.sub(r'\{@link #?([^}]*)\}', r'`\1`', re.sub(r'\{@code ([^}]*)\}', r'`\1`', c)))
                   .replace('<p>', '').replace('<pre>', '```text').replace('</pre>', '```')
                   # The rest of the HTML a Javadoc comment uses, as the Markdown that means the same.
                   .replace('<b>', '**').replace('</b>', '**')
                   .replace('<ul>', '').replace('</ul>', '').replace('<li>', '- ').replace('</li>', '')
                   .replace('&lt;', '<').replace('&gt;', '>')
                   for c in comment if c]
            i += 1
            continue
        if s.startswith('//') or s.startswith('*'):
            i += 1
            continue
        m = re.match(r'^\s*public (?:static )?(?:final )?(?:abstract )?(class|@?interface) (\w+)', line)
        if m:
            name = m.group(2)
            full = '.'.join([c for c, _ in stack] + [name])
            kind = 'annotation' if m.group(1) == '@interface' else m.group(1)
            items.append((area, kind, full, s.rstrip(' {'), doc, ''))
            stack.append((name, depth))
            doc = []
            depth += line.count('{') - line.count('}')
            i += 1
            continue
        # An anonymous class (`return new Iterator<Value>() {`): its public methods are not API.
        if re.search(r'\bnew [\w.]+(?:<[^>]*>)?\(\)\s*\{\s*$', line):
            stack.append(('', depth))
            doc = []
            depth += line.count('{') - line.count('}')
            i += 1
            continue
        m = re.match(r'^\s*public (?:static )?(?:final )?(?:[\w\[\]<>.]+ )(\w+)\(([^)]*)\)', line)
        if m and stack:
            if stack[-1][0]:
                name = f'{stack[-1][0]}.{m.group(1)}'
                items.append((area, 'method', name, s.rstrip(' {').strip(), doc, ''))
            doc = []
            depth += line.count('{') - line.count('}')
            i += 1
            continue
        m = re.match(r'^\s*public (?:static )?(?:final )?(?:[\w\[\]<>.]+ )(\w+)\s*(=|;)', line)
        if m and stack and '(' not in line.split('=')[0]:
            name = f'{stack[-1][0]}.{m.group(1)}'
            items.append((area, 'field', name, s.rstrip(';').strip(), doc, ''))
            doc = []
            i += 1
            continue
        depth += line.count('{') - line.count('}')
        while stack and depth <= stack[-1][1]:
            stack.pop()
        if s == '':
            doc = []
        i += 1
    return items


def parse_java_all():
    items = []
    for area, name in JAVA_FILES:
        items.extend(parse_java(os.path.join(JAVA_DIR, name), area))
    return items


