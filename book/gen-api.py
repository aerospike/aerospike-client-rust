LANG = {'rust': 'rust', 'go': 'go', 'c': 'c', 'cpp': 'cpp', 'java': 'java'}


# ---------------------------------------------------------------- c++

CPP_EVENT_SECTIONS = ('Events', 'The macros')


def escape_generics(doc):
    """The doc lines with the template arguments outside backticks escaped, so Markdown does not read
    `Result<void>` as an HTML tag. Backtick spans may cross lines, so the parity runs over the block."""
    parts = '\n'.join(doc).split('`')
    for k in range(0, len(parts), 2):
        parts[k] = re.sub(r'<([\w\s,:]+)>', r'&lt;\1&gt;', parts[k])
    return '`'.join(parts).split('\n')


def cpp_signature(s):
    """A declaration line without the body that may follow it on the same line."""
    m = re.match(r'^(.*?\)(?:\s*const)?(?:\s*noexcept)?(?:\s*->\s*[\w:<>]+)?)\s*\{.*$', s)
    if m:
        return m.group(1).strip()
    m = re.match(r'^((?:template <[^>]*>\s*)?(?:class|struct) \w+(?:\s*:\s*[\w:]+)?)\s*\{.*$', s)
    if m:
        return m.group(1).strip()
    return s.rstrip(' {').strip()


def parse_cpp(path):
    """The public types, their public methods, the free functions and the UDF_* macros of the C++ header,
    each with the `//` comment above it. A `//====` line followed by `// Title` starts a section; the
    area is events for the event section and the UDF_ON_* macros, stream for the stream macros, record
    otherwise."""
    lines = open(path, encoding='utf-8').read().split('\n')
    items = []
    section = ''
    doc = []
    stack = []  # (type name, brace depth at which it opened, visible)
    depth = 0
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        s = line.strip()
        if s.startswith('//====') and i + 1 < n and lines[i + 1].startswith('// '):
            section = lines[i + 1][3:].rstrip('.').strip()
            i += 2
            while i < n and lines[i].startswith('//'):
                i += 1
            continue
        if s.startswith('//'):
            doc.append(s[2:].strip())
            i += 1
            continue
        area = 'events' if section.startswith(CPP_EVENT_SECTIONS) else 'record'
        in_detail = any(name == 'detail' for name, _, _ in stack)
        m = re.match(r'^namespace (\w+)', line)
        if m:
            stack.append((m.group(1), depth, False))
            depth += line.count('{') - line.count('}')
            i += 1
            continue
        m = re.match(r'^(?:template <[^>]*>\s*)?(?:class|struct) (\w+)(?:\s*:\s*[\w:]+)?\s*\{', line)
        if m and not in_detail:
            name = m.group(1)
            outer = [t for t, _, v in stack if v]
            full = '::'.join(outer + [name])
            items.append((area, 'type', full, cpp_signature(s), doc, ''))
            net = line.count('{') - line.count('}')
            if net > 0:
                stack.append((name, depth, True))
            doc = []
            depth += net
            i += 1
            continue
        if s in ('private:', 'protected:') and stack and stack[-1][2]:
            stack[-1] = (stack[-1][0], stack[-1][1], 'hidden')
            doc = []
            i += 1
            continue
        if s == 'public:' and stack and stack[-1][2]:
            stack[-1] = (stack[-1][0], stack[-1][1], True)
            doc = []
            i += 1
            continue
        if stack and stack[-1][2] is True and depth == stack[-1][1] + 1:
            m = re.match(r'^\t(?:template <[^>]*>\s*)?(?:static |constexpr |explicit |inline )*([\w:<>,&*\s]+?)\s+([a-z_]\w*)\(', line)
            if m and not s.startswith('return') and 'operator' not in s:
                items.append((area, 'method', f'{stack[-1][0]}::{m.group(2)}', cpp_signature(s), doc, ''))
                doc = []
                depth += line.count('{') - line.count('}')
                i += 1
                continue
        if not stack or (stack[-1][0] == 'udf' and depth == 1):
            m = re.match(r'^(?:template <[^>]*>\s*)?(?:inline |constexpr |static )*([\w:<>,&*\s]+?)\s+([a-z_]\w*)\(', line)
            if m and not in_detail and not s.startswith('#'):
                items.append((area, 'function', m.group(2), cpp_signature(s), doc, ''))
                doc = []
                depth += line.count('{') - line.count('}')
                i += 1
                continue
        m = re.match(r'^#define (UDF_[A-Z_]+)(\([^)]*\))?', line)
        if m and not m.group(1).startswith(('UDF_EVENT_', 'UDF_HANDLER_SIG', 'UDF_SIG_EXPORT')):
            macro = m.group(1)
            macro_area = 'events' if macro.startswith('UDF_ON_') else 'stream' if macro.startswith('UDF_STREAM') else 'record'
            items.append((macro_area, 'macro', macro, (macro + (m.group(2) or '')).strip(), doc, ''))
            doc = []
            while i < n and lines[i].rstrip().endswith('\\'):
                i += 1
            i += 1
            continue
        depth += line.count('{') - line.count('}')
        while stack and depth <= stack[-1][1]:
            stack.pop()
        if s == '':
            doc = []
        i += 1
    return items

AREA_TITLE = {'record': 'Record UDFs', 'stream': 'Stream UDFs', 'events': 'Events'}


def render(lang, items, area, intro):
    out = [intro, '']
    if not items:
        out.append('_No items of this area are specific to this SDK; see the record UDF reference._')
        return '\n'.join(out)
    for area_, kind, name, signature, doc, body in items:
        out.append(f'#### `{name}`')
        out.append('')
        code = body if body else signature
        if code:
            out.append(f'```{LANG[lang]}')
            out.append(code)
            out.append('```')
            out.append('')
        if doc:
            out.append('\n'.join(escape_generics(doc)))
            out.append('')
    return '\n'.join(out)


def write(lang, items):
    os.makedirs(OUT, exist_ok=True)
    for area in ('record', 'stream', 'events'):
        selected = [it for it in items if it[0] == area]
        intro = f'<!-- generated by book/gen-api.py from the {lang} SDK; do not edit -->'
        with open(os.path.join(OUT, f'{lang}-{area}.md'), 'w', encoding='utf-8') as f:
            f.write(render(lang, selected, area, intro))
            f.write('\n')
        print(f'{lang}-{area}: {len(selected)} items')


if __name__ == '__main__':
    write('rust', parse_rust(RUST))
    write('go', parse_go_all())
    write('c', parse_c(C))
    write('cpp', parse_cpp(CPP))
    write('java', parse_java_all())
